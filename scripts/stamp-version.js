const { execSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const outPath = path.join(__dirname, '..', 'src', 'config', 'buildInfo.ts');

function runGit(cmd) {
  return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
}

try {
  const commitCount = runGit('git rev-list --count HEAD');
  const shortSha = runGit('git rev-parse --short HEAD');
  const version = `1.0.${commitCount}`;
  const label = `v${version} (${shortSha})`;

  const content = `// Auto-generated by scripts/stamp-version.js\nexport const BUILD_INFO = {\n  version: '${version}',\n  commit: '${shortSha}',\n  label: '${label}',\n} as const;\n`;

  fs.writeFileSync(outPath, content, 'utf8');
  console.log(`Stamped build version: ${label}`);
} catch {
  if (!fs.existsSync(outPath)) {
    const fallback = `export const BUILD_INFO = {\n  version: '1.0.0',\n  commit: 'dev',\n  label: 'v1.0.0 (dev)',\n} as const;\n`;
    fs.writeFileSync(outPath, fallback, 'utf8');
  }
}

